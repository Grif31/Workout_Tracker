// Writes the badge sheet's geometry to the app as constants/badgeArt.ts, so
// AchievementBadge draws exactly what the canvas draws. Rerun after any change
// to the sheet (and after layout.js + splice.js):
//   node export_rn.js ../canvas/Badges.dc.html ../../../src/workout-tracker-native/constants/badgeArt.ts
const fs = require('fs');
const ClipperLib = require('clipper-lib');

const [, , sheet, out] = process.argv;
if (!sheet || !out) {
  console.error('usage: node export_rn.js <Badges.dc.html> <badgeArt.ts>');
  process.exit(1);
}
const html = fs.readFileSync(sheet, 'utf8');
const js = html.match(/<script type="text\/x-dc" data-dc-script[^>]*>([\s\S]*?)<\/script>/)[1];
const S = new Function('DCLogic', js + '\nreturn { SH, IC, ICT, STY, BANDS, SHAPED_CROWNS, CROWN, DETAIL, EXTRA, VEINS, BAND, barbell };')(class {});

// Gradient stops straight from the sheet's <defs>
function stops(id) {
  const m = html.match(new RegExp('<(?:linear|radial)Gradient id="' + id + '"[^>]*>([\\s\\S]*?)</(?:linear|radial)Gradient>'));
  if (!m) throw new Error('no gradient ' + id);
  return [...m[1].matchAll(/offset="([\d.]+)" style="stop-color: (#[0-9A-Fa-f]{6});(?: stop-opacity: ([\d.]+);)?/g)]
    .map((s) => (s[3] !== undefined ? [Number(s[1]), s[2], Number(s[3])] : [Number(s[1]), s[2]]));
}

function transform(t) {
  if (!t) return null;
  const m = t.match(/translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)/);
  return [Number(m[1]), Number(m[2]), Number(m[3])];
}

// The badge back's text has to fit the face: for each whole y in the 64 box,
// the widest free span (centre, half-width) inside the band's inner edge (4.5 + 1.5)
// less a 1.5 gap, so BadgeBack can size each line to the outline at its height.
const src = fs.readFileSync(__dirname + '/bbox.js', 'utf8');
const sample = eval('(' + src.match(/function bbox\(d\)\{[\s\S]*?\n\}/)[0].replace('const xs=pts.map', 'return pts;const xs=pts.map') + ')');
const BACK_INSET = 4.5 + 1.5 + 1.5;
function inset(pts, d) {
  const K = 1000;
  const co = new ClipperLib.ClipperOffset(2, 0.05 * K);
  co.AddPath(pts.map(([x, y]) => ({ X: Math.round(x * K), Y: Math.round(y * K) })), ClipperLib.JoinType.jtRound, ClipperLib.EndType.etClosedPolygon);
  const sol = new ClipperLib.Paths(); co.Execute(sol, -d * K);
  sol.sort((a, b) => Math.abs(ClipperLib.Clipper.Area(b)) - Math.abs(ClipperLib.Clipper.Area(a)));
  return sol.length ? sol[0].map((p) => [p.X / K, p.Y / K]) : [];
}
function backRows(d) {
  const poly = inset(sample(d), BACK_INSET);
  const rows = [];
  for (let y = 0; y <= 64; y++) {
    const xs = [];
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [xi, yi] = poly[i], [xj, yj] = poly[j];
      if ((yi > y) !== (yj > y)) xs.push(xi + (y - yi) * (xj - xi) / (yj - yi));
    }
    xs.sort((a, b) => a - b);
    let best = [32, 0];
    for (let k = 0; k + 1 < xs.length; k += 2) {
      const half = (xs[k + 1] - xs[k]) / 2;
      if (half > best[1]) best = [Math.round((xs[k] + half) * 10) / 10, Math.floor(half * 10) / 10];
    }
    rows.push(best);
  }
  return rows;
}

const keys = Object.keys(S.SH);
const art = {};
for (const k of keys) {
  art[k] = {
    shape: S.SH[k],
    band: S.BANDS[k] || '',
    icon: S.IC[k] || '',
    iconT: transform(S.ICT[k]),
    stampY: S.STY[k] ?? 52,
    extra: S.EXTRA[k] || '',
    detail: S.DETAIL[k] || '',
    crown: S.SHAPED_CROWNS[k] || null,
    backRows: backRows(S.SH[k]),
  };
}

const metals = {};
for (const m of ['bronze', 'silver', 'gold', 'marble', 'locked']) {
  metals[m] = { face: stops('m-' + m), rim: stops('r-' + m), ink: stops('i-' + m), iconInk: stops('j-' + m), band: S.BAND[m] };
}

const plates = [1, 2, 3, 4].map((n) => S.barbell(n));

const body = `// GENERATED by design/achievements/tools/export_rn.js from canvas/Badges.dc.html.
// Do not edit by hand: change the sheet, then rerun the script (see design/achievements/README.md).
/* eslint-disable */

export type BadgeArtKey = ${keys.map((k) => `'${k}'`).join(' | ')};
export type BadgeMetal = 'bronze' | 'silver' | 'gold' | 'marble' | 'locked';
/** [offset, color] or [offset, color, opacity] */
export type GradientStop = [number, string] | [number, string, number];

export interface BadgeArt {
  shape: string;
  /** The key band: the outline inset an even 4.5 units */
  band: string;
  icon: string;
  /** translate x, translate y, scale; null draws the icon as is */
  iconT: [number, number, number] | null;
  stampY: number;
  /** Finials and fittings outside the face, drawn in the rim metal */
  extra: string;
  /** Engraved lines on the custom badges */
  detail: string;
  /** Olive crown for the top rung, traced around this outline; null wears ROUND_CROWN */
  crown: string | null;
  /** By whole y (0 to 64): [centre x, half-width] of the widest span a back line may use there */
  backRows: [number, number][];
}

export const BADGE_ART: Record<BadgeArtKey, BadgeArt> = {
${Object.entries(art).map(([k, v]) => `  ${k}: {
${Object.entries(v).map(([f, x]) => `    ${f}: ${JSON.stringify(x)},`).join(String.fromCharCode(10))}
  },`).join(String.fromCharCode(10))}
};

export const BADGE_METALS: Record<BadgeMetal, {
  face: GradientStop[]; rim: GradientStop[]; ink: GradientStop[]; iconInk: GradientStop[];
  /** key band stroke width and dash ('none' for solid) */
  band: [number, string];
}> = {
${Object.entries(metals).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join(String.fromCharCode(10))}
};

export const ROUND_CROWN = ${JSON.stringify(S.CROWN)};
export const MARBLE_VEINS = ${JSON.stringify(S.VEINS)};
export const GLOSS_STOPS: GradientStop[] = ${JSON.stringify(stops('gloss'))};
export const GLINT_STOPS: GradientStop[] = ${JSON.stringify(stops('spec'))};

/** The plaque's bar with 1 to 4 plates a side, by plate count - 1 */
export const PLATE_BARS: string[] = ${JSON.stringify(plates)};
/** Embolimos' extra peg, filled */
export const LEAP_PEG = 'M46 28 a2 2 0 1 0 .01 0 Z';
`;
fs.writeFileSync(out, body);
console.log('wrote', out, keys.length, 'shapes');
